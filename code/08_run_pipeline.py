from pathlib import Path
import argparse
import subprocess
import sys
import shutil
import json
import time
from datetime import datetime

import pandas as pd

# ---------------------------------------------------------------------
# Make sure the project root is imported before Python's built-in
# "code.py" module.
# ---------------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parent.parent

if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from code import config


# ---------------------------------------------------------------------
# Utility: run one pipeline step
# ---------------------------------------------------------------------
def run_step(script_name, arguments):
    script_path = PROJECT_ROOT / "code" / script_name

    if not script_path.exists():
        raise FileNotFoundError(
            f"Pipeline script not found:\n{script_path}"
        )

    command = [
        sys.executable,
        str(script_path)
    ] + [str(x) for x in arguments]

    print()
    print("=" * 75)
    print(f"RUNNING STEP: {script_name}")
    print("=" * 75)
    print("Command:")
    print(" ".join(command))
    print()

    result = subprocess.run(
        command,
        cwd=str(PROJECT_ROOT)
    )

    if result.returncode != 0:
        raise RuntimeError(
            f"\nPipeline stopped.\n"
            f"Script: {script_name}\n"
            f"Exit code: {result.returncode}"
        )


# ---------------------------------------------------------------------
# Utility: safely remove only files generated by the current pipeline
# ---------------------------------------------------------------------
def clear_pipeline_outputs():
    files_to_clear = [
        config.VALIDATED_FILE,
        config.INVALID_FILE,
        config.DUPLICATES_FILE,
        config.DRUG_LIKENESS_FILE,
        config.ADMET_AI_FILE,
        config.DNN_PREDICTIONS_FILE,
        config.SAFETY_COMPARISON_FILE,
        config.SAFETY_SCORES_FILE,
        config.SENSITIVITY_FILE,
        config.REWARD_FILE,
        config.RECOMMENDED_FILE,
        config.RUN_SUMMARY_FILE,
    ]

    print()
    print("=" * 75)
    print("CLEARING CURRENT PIPELINE OUTPUTS")
    print("=" * 75)

    for file_path in files_to_clear:

        file_path = Path(file_path)

        if not file_path.exists():
            continue

        try:
            file_path.unlink()

            print(
                f"Removed: {file_path.name}"
            )

        except PermissionError:

            raise PermissionError(
                "\n\nWINDOWS FILE LOCK DETECTED\n"
                "----------------------------------------\n"
                f"File:\n{file_path}\n\n"
                "This file is being used by another program.\n"
                "Close Excel, VS Code, Notepad, pandas viewers, "
                "or any other program currently using this CSV.\n\n"
                "Then run the pipeline again.\n"
            )


# ---------------------------------------------------------------------
# Utility: verify required trained DNN model exists
# ---------------------------------------------------------------------
def verify_trained_model():

    required_models = [
        config.DNN_MODEL_FILE,
        config.DNN_SCALER_FILE,
        config.DNN_CONFIG_FILE,
    ]

    print()
    print("=" * 75)
    print("CHECKING TRAINED DNN")
    print("=" * 75)

    for model_file in required_models:

        model_file = Path(model_file)

        if not model_file.exists():

            raise FileNotFoundError(
                "\nRequired trained DNN file is missing:\n"
                f"{model_file}\n\n"
                "Train the Module 3 DNN first using:\n"
                "python code\\04_multitask_dnn.py --epochs 2 --seed 42"
            )

        print(
            f"OK: {model_file.name}"
        )


# ---------------------------------------------------------------------
# Utility: create run archive
# ---------------------------------------------------------------------
def archive_run(run_name, start_time, seed):

    timestamp = datetime.now().strftime(
        "%Y%m%d_%H%M%S"
    )

    safe_name = "".join(
        character
        if character.isalnum() or character in "-_"
        else "_"
        for character in run_name
    )

    run_directory = (
        Path(config.RUNS_DIR)
        / f"{timestamp}_{safe_name}"
    )

    run_directory.mkdir(
        parents=True,
        exist_ok=True
    )

    print()
    print("=" * 75)
    print("ARCHIVING RUN")
    print("=" * 75)

    output_files = [
        config.VALIDATED_FILE,
        config.INVALID_FILE,
        config.DUPLICATES_FILE,
        config.DRUG_LIKENESS_FILE,
        config.ADMET_AI_FILE,
        config.DNN_PREDICTIONS_FILE,
        config.SAFETY_COMPARISON_FILE,
        config.SAFETY_SCORES_FILE,
        config.SENSITIVITY_FILE,
        config.REWARD_FILE,
        config.RECOMMENDED_FILE,
    ]

    archived_files = []

    for source in output_files:

        source = Path(source)

        if not source.exists():
            continue

        destination = (
            run_directory
            / source.name
        )

        try:

            shutil.copy2(
                source,
                destination
            )

            archived_files.append(
                source.name
            )

            print(
                f"Archived: {source.name}"
            )

        except PermissionError:

            raise PermissionError(
                "\nUnable to archive file because it is locked:\n"
                f"{source}\n\n"
                "Close the program using this file and rerun."
            )

    # -------------------------------------------------------------
    # Archive trained model information.
    # -------------------------------------------------------------
    model_directory = (
        run_directory / "models"
    )

    model_directory.mkdir(
        parents=True,
        exist_ok=True
    )

    model_files = [
        config.DNN_MODEL_FILE,
        config.DNN_SCALER_FILE,
        config.DNN_CONFIG_FILE,
    ]

    archived_models = []

    for source in model_files:

        source = Path(source)

        if not source.exists():
            continue

        destination = (
            model_directory
            / source.name
        )

        shutil.copy2(
            source,
            destination
        )

        archived_models.append(
            source.name
        )

    # -------------------------------------------------------------
    # Calculate run statistics.
    # -------------------------------------------------------------
    runtime_seconds = (
        time.perf_counter()
        - start_time
    )

    summary = {
        "run_name": run_name,
        "timestamp": timestamp,
        "seed": int(seed),
        "runtime_seconds": round(
            runtime_seconds,
            3
        ),
        "archived_files": archived_files,
        "archived_models": archived_models,
    }

    # -------------------------------------------------------------
    # Safety statistics
    # -------------------------------------------------------------
    safety_file = Path(
        config.SAFETY_SCORES_FILE
    )

    if safety_file.exists():

        safety_df = pd.read_csv(
            safety_file
        )

        summary[
            "candidate_count"
        ] = int(len(safety_df))

        if "safety_score" in safety_df.columns:

            summary[
                "mean_safety_score"
            ] = float(
                safety_df[
                    "safety_score"
                ].mean()
            )

            summary[
                "min_safety_score"
            ] = float(
                safety_df[
                    "safety_score"
                ].min()
            )

            summary[
                "max_safety_score"
            ] = float(
                safety_df[
                    "safety_score"
                ].max()
            )

        if "hard_fail" in safety_df.columns:

            summary[
                "hard_fail_count"
            ] = int(
                safety_df[
                    "hard_fail"
                ]
                .fillna(False)
                .astype(bool)
                .sum()
            )

        if "safety_status" in safety_df.columns:

            summary[
                "safety_status_counts"
            ] = {
                str(key): int(value)
                for key, value
                in safety_df[
                    "safety_status"
                ]
                .value_counts()
                .to_dict()
                .items()
            }

    # -------------------------------------------------------------
    # Reward statistics
    # -------------------------------------------------------------
    reward_file = Path(
        config.REWARD_FILE
    )

    if reward_file.exists():

        reward_df = pd.read_csv(
            reward_file
        )

        summary[
            "ranked_count"
        ] = int(len(reward_df))

        if "reward" in reward_df.columns:

            summary[
                "mean_reward"
            ] = float(
                reward_df[
                    "reward"
                ].mean()
            )

            summary[
                "max_reward"
            ] = float(
                reward_df[
                    "reward"
                ].max()
            )

        if "affinity_missing" in reward_df.columns:

            summary[
                "missing_affinity_count"
            ] = int(
                reward_df[
                    "affinity_missing"
                ]
                .fillna(False)
                .astype(bool)
                .sum()
            )

    # -------------------------------------------------------------
    # Recommended shortlist statistics
    # -------------------------------------------------------------
    recommended_file = Path(
        config.RECOMMENDED_FILE
    )

    if recommended_file.exists():

        recommended_df = pd.read_csv(
            recommended_file
        )

        summary[
            "recommended_count"
        ] = int(
            len(recommended_df)
        )

    # -------------------------------------------------------------
    # Model version information
    # -------------------------------------------------------------
    try:

        import torch

        summary[
            "torch_version"
        ] = torch.__version__

    except Exception:

        summary[
            "torch_version"
        ] = "unknown"

    try:

        import rdkit

        summary[
            "rdkit_version"
        ] = rdkit.__version__

    except Exception:

        summary[
            "rdkit_version"
        ] = "unknown"

    try:

        import admet_ai

        summary[
            "admet_ai_version"
        ] = getattr(
            admet_ai,
            "__version__",
            "unknown"
        )

    except Exception:

        summary[
            "admet_ai_version"
        ] = "unknown"

    try:

        import pandas

        summary[
            "pandas_version"
        ] = pandas.__version__

    except Exception:

        summary[
            "pandas_version"
        ] = "unknown"

    # -------------------------------------------------------------
    # Save summary inside archive.
    # -------------------------------------------------------------
    summary_file = (
        run_directory
        / "run_summary.json"
    )

    with open(
        summary_file,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            summary,
            file,
            indent=2
        )

    print(
        f"\nRun summary: {summary_file}"
    )

    return run_directory, summary


# ---------------------------------------------------------------------
# Main pipeline
# ---------------------------------------------------------------------
def main():

    parser = argparse.ArgumentParser(
        description=(
            "Module 3 - Complete "
            "Multi-Endpoint Drug Safety Pipeline"
        )
    )

    parser.add_argument(
        "--ligands",
        required=True,
        help=(
            "Input ligand CSV containing "
            "candidate_id and smiles"
        )
    )

    parser.add_argument(
        "--affinity",
        required=True,
        help=(
            "Affinity CSV containing "
            "candidate_id and affinity_norm"
        )
    )

    parser.add_argument(
        "--name",
        required=True,
        help="Name used for the archived run"
    )

    parser.add_argument(
        "--seed",
        type=int,
        default=config.SEED,
        help="Random seed"
    )

    args = parser.parse_args()

    ligand_file = Path(
        args.ligands
    )

    affinity_file = Path(
        args.affinity
    )

    # -------------------------------------------------------------
    # Validate input files before deleting anything.
    # -------------------------------------------------------------
    if not ligand_file.exists():

        raise FileNotFoundError(
            f"Ligand file not found:\n"
            f"{ligand_file}"
        )

    if not affinity_file.exists():

        raise FileNotFoundError(
            f"Affinity file not found:\n"
            f"{affinity_file}"
        )

    # -------------------------------------------------------------
    # Check project configuration.
    # -------------------------------------------------------------
    config.SEED = args.seed

    config.dirs()
    config.check()

    # -------------------------------------------------------------
    # Verify trained DNN before starting.
    # -------------------------------------------------------------
    verify_trained_model()

    start_time = time.perf_counter()

    print()
    print("=" * 75)
    print("MODULE 3 - COMPLETE SAFETY PIPELINE")
    print("=" * 75)

    print(
        f"Project : {PROJECT_ROOT}"
    )

    print(
        f"Ligands : {ligand_file}"
    )

    print(
        f"Affinity: {affinity_file}"
    )

    print(
        f"Name    : {args.name}"
    )

    print(
        f"Seed    : {args.seed}"
    )

    # -------------------------------------------------------------
    # Clear only pipeline-generated outputs.
    # -------------------------------------------------------------
    clear_pipeline_outputs()

    # =============================================================
    # STEP 1 - VALIDATION
    # =============================================================
    run_step(
        "01_validate.py",
        [
            "--ligands",
            ligand_file,
            "--seed",
            args.seed
        ]
    )

    # =============================================================
    # STEP 2 - DRUG LIKENESS
    # =============================================================
    run_step(
        "02_drug_likeness.py",
        [
            "--input",
            config.VALIDATED_FILE
        ]
    )

    # =============================================================
    # STEP 3 - ADMET-AI
    # =============================================================
    run_step(
        "03_admet_ai.py",
        [
            "--input",
            config.VALIDATED_FILE
        ]
    )

    # =============================================================
    # STEP 4 - TRAINED DNN INFERENCE
    #
    # IMPORTANT:
    # This does NOT retrain the DNN.
    # It loads:
    # models\multitask_safety_dnn.pt
    # =============================================================
    run_step(
        "04b_dnn_inference.py",
        [
            "--input",
            config.VALIDATED_FILE
        ]
    )

    # =============================================================
    # STEP 5 - DNN VS ADMET-AI
    # =============================================================
    run_step(
        "05_safety_combine.py",
        []
    )

    # =============================================================
    # STEP 6 - SAFETY SCORE
    # =============================================================
    run_step(
        "06_safety_score.py",
        [
            "--seed",
            args.seed
        ]
    )

    # =============================================================
    # STEP 6B - SENSITIVITY ANALYSIS
    # =============================================================
    run_step(
        "06_sensitivity.py",
        [
            "--input",
            config.SAFETY_COMPARISON_FILE,
            "--seed",
            args.seed
        ]
    )

    # =============================================================
    # STEP 7 - AFFINITY + SAFETY REWARD/RANKING
    # =============================================================
    run_step(
        "07_reward_rank.py",
        [
            "--affinity",
            affinity_file,
            "--seed",
            args.seed
        ]
    )

    # =============================================================
    # ARCHIVE
    # =============================================================
    run_directory, summary = archive_run(
        args.name,
        start_time,
        args.seed
    )

    runtime = (
        time.perf_counter()
        - start_time
    )

    print()
    print("=" * 75)
    print("MODULE 3 PIPELINE COMPLETE")
    print("=" * 75)

    print(
        f"Runtime           : {runtime:.2f} seconds"
    )

    print(
        f"Archive directory : {run_directory}"
    )

    print(
        f"Safety scores     : "
        f"{config.SAFETY_SCORES_FILE}"
    )

    print(
        f"Reward ranking    : "
        f"{config.REWARD_FILE}"
    )

    print(
        f"Recommended       : "
        f"{config.RECOMMENDED_FILE}"
    )

    print(
        f"Sensitivity       : "
        f"{config.SENSITIVITY_FILE}"
    )

    print(
        f"Run summary       : "
        f"{run_directory / 'run_summary.json'}"
    )

    print()
    print("Pipeline finished successfully.")


if __name__ == "__main__":
    main()